-- Find the change over time sales "trndes" 
SELECT
 year(Purchase_Date) AS order_year,
 month(Purchase_Date) AS order_month,
 SUM(Purchase_Amount)  AS total_sales,
 COUNT(DISTINCT Customer_ID) AS total_custmers
FROM walmart
GROUP BY year(Purchase_Date),  month(Purchase_Date)
ORDER BY year(Purchase_Date),  month(Purchase_Date);

-- Claculate total sales per mont
-- and the runinng total over time
SELECT
order_date,
total_sales,
SUM(total_sales) OVER(PARTITION BY order_date ORDER BY order_date) AS running_total,
AVG(sales_avg) OVER(ORDER BY order_date) AS moving_avg
FROM(
SELECT
 month(Purchase_Date) AS order_date, 
 SUM(Purchase_Amount) AS total_sales,
 AVG(Purchase_Amount) AS sales_avg
FROM walmart
GROUP BY month(Purchase_Date))t;

-- Anayze the yearly preformance of products by comparing their sales
WITH yearly_product_sales AS
(
SELECT 
year(Purchase_Date) AS year_order,
Product_Name,
SUM(Purchase_Amount) AS current_sales
FROM walmart
GROUP BY year(Purchase_Date), Product_Name)
SELECT 
year_order,
Product_Name,
current_sales,
ROUND(AVG(current_sales) OVER(PARTITION BY Product_Name),0) AS product_avg,
current_sales - ROUND(AVG(current_sales) OVER(PARTITION BY Product_Name),0) AS diff_avg
FROM yearly_product_sales
GROUP BY Product_Name, year_order;