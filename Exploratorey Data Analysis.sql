-- Date Exploration
# Identfy the earliest and latest dates "Boundaries"
# Understand the scop of data and the timespan

-- Find the fist & last purchase date
-- How many months of sales are avilable
SELECT
 MIN(Purchase_Date) AS first_purchas,
 MAX(Purchase_Date) AS last_purchas,
 timestampdiff(month, MIN(Purchase_Date), MAX(Purchase_Date)) As purchase_range_months
FROM walmart;

-- Find the youngest and oldest customer
SELECT
 MIN(age) AS youngest,
 MAX(Age) AS oldest
FROM walmart;


