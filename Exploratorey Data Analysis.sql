# Ranking
-- Wich 5 products generate the highest revenue and rated as 5
SELECT *
FROM (
SELECT 
	Product_Name,
    SUM(Purchase_Amount) AS highest_revenue,
ROW_NUMBER() OVER(ORDER BY SUM(Purchase_Amount) DESC) AS rank_products
FROM walmart
GROUP BY Product_Name) t
WHERE rank_products <= 5;

-- Any product that rated under 2 flag  as worest 
